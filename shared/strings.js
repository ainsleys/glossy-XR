// The strings the page and the headset panel show a contributor, in each
// interface language. No dependencies, so the same file runs in Node (the unit
// test) and the browser.
//
// Keys are readable ids with a prefix for where the text appears: consent.*,
// status.* (the status line, also on the headset panel), hint.* (the key hint
// and the headset panel's hints), chat.* (the headset chat panel), list.* (the
// clip list and clip descriptions) and html.* (fixed page text). Operator
// panels, logs and the server stay English and are not here.
//
// Variables are {name}. In Turkish a variable takes a postposition ("{object}
// üzerinde"), never a case suffix, because the suffix depends on the word that
// fills it. Plural forms are separate keys (.one, .other) and the caller picks
// one; Turkish uses the same form for both, with no plural after a number.
//
// To add a language: add a block under STRINGS with every key of `en`, run
// `npm run test:unit`, and have a speaker of the language read it. Turkish is
// signed off with `node scripts/sign-off-tr.mjs --by "<name>"` (TR_REVIEWED below).

