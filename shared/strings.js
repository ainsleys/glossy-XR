/** The string for `key` in `lang` (English when the key or language is missing), with {name} filled from `vars`. */
export function t(key, vars = {}, lang = 'en') {
  const s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}

/** A number with `digits` decimals and the language's decimal separator, without grouping (1.2 in English, 1,2 in Turkish). */
export function num(x, digits, lang = 'en') {
  try { return new Intl.NumberFormat(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits, useGrouping: false }).format(x); } catch { return x.toFixed(digits); }
}

